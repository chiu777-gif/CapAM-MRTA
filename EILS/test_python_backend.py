"""Python/C++ parity, MT19937-64 reference vectors and compiler independence."""
import contextlib
import io
from pathlib import Path
import shutil
import tempfile
import unittest
from unittest.mock import patch

import numpy as np

from EILS.evaluate import main as evaluate
from EILS.python_solver import MT19937_64, Search
from EILS.solver import prepare, solve, validate_solution
from EILS.test_solver import instance
from EILS.verify_results import verify
from problems.mrta.data import load_file_dataset


class PythonBackendTests(unittest.TestCase):
    def test_rng_matches_cpp_reference_across_twists(self):
        # Generated by std::mt19937_64 with g++ at indices 0,1,311,312,623,624.
        expected = {
            0: [2947667278772165694, 18301848765998365067, 11228354904504431959,
                17661967264253682746, 12220678344985132467, 13999015252384676179],
            5489: [14514284786278117030, 4620546740167642908, 1370093900783164344,
                   6776537281339823025, 15547153445796060183, 12329720415526259303],
            2**64 - 1: [478026398904862820, 13243134898385798468, 8835741269252529079,
                       17926718052445221126, 12758722211879373259, 13753320293866618415],
        }
        for seed, reference in expected.items():
            rng = MT19937_64(seed)
            actual = [rng() for _ in range(625)]
            self.assertEqual([actual[index] for index in (0, 1, 311, 312, 623, 624)], reference)

    @unittest.skipUnless(shutil.which("g++"), "C++ parity needs g++; Python backend does not")
    def test_backends_agree_on_routes_stats_and_finish_times(self):
        generator = np.random.RandomState(923)
        for _ in range(8):
            data = prepare(instance(generator.rand(13, 2), generator.rand(3, 2),
                                    generator.uniform(0.5, 2.5, 13), generator.uniform(0, 0.5, 13),
                                    generator.uniform(0.5, 1.5, 3)))
            for algorithm in ("construct", "ils", "eils"):
                for profile in ("tight", "slack"):
                    for service_time in ("continuous", "ceil"):
                        kwargs = dict(algorithm=algorithm, profile=profile, service_time=service_time,
                                      limit=20, seed=2**64 - 1)
                        python = solve(data, backend="python", **kwargs)
                        cpp = solve(data, backend="cpp", **kwargs)
                        self.assertEqual(python["routes"], cpp["routes"])
                        for name in ("native_completed_tasks", "iterations", "best_iteration"):
                            self.assertEqual(python[name], cpp[name])
                        np.testing.assert_array_equal(python["robots"], cpp["robots"])
                        np.testing.assert_allclose(python["finish_times"], cpp["finish_times"], atol=1e-10, rtol=1e-12)
                        validate_solution(data, python, service_time)

    def test_python_is_default_and_does_not_load_cpp(self):
        data = prepare(instance([[0, 0], [0, 0]], [[0, 0]], [1, 1.5]))
        with patch("EILS.solver.build", side_effect=AssertionError("C++ build called")), \
                patch("EILS.solver.library", side_effect=AssertionError("C++ library called")):
            result = solve(data, limit=3)
        self.assertEqual(validate_solution(data, result)["tasks_done"], 1)
        with self.assertRaises(ValueError):
            solve(data, backend="unknown")

    @unittest.skipUnless(shutil.which("g++"), "C++ parity needs g++")
    def test_taptc_near_equal_insertion_cost_regression(self):
        here = Path(__file__).resolve().parent
        dataset = load_file_dataset([here.parent / "data/mrta_gini"])
        data = prepare(dataset[7])  # r11a5i01: math.hypot's rounding changed two visits.
        options = dict(algorithm="ils", profile="tight", seed=20261032, limit=20)
        python = solve(data, backend="python", **options)
        cpp = solve(data, backend="cpp", **options)
        self.assertEqual(python["routes"], cpp["routes"])
        self.assertEqual(python["iterations"], cpp["iterations"])
        self.assertEqual(python["best_iteration"], cpp["best_iteration"])
        self.assertAlmostEqual(validate_solution(data, python)["cost"], validate_solution(data, cpp)["cost"], places=10)

    def test_circular_removal_and_empty_tours(self):
        data = prepare(instance([[i, 0] for i in range(6)], [[0, 0], [0, 0]], [20] * 6))
        search = Search(data, "continuous")
        search.tours = [list(range(6)), []]
        search.used[:] = True
        search.shake(3, 4, False, MT19937_64(1))
        self.assertEqual(search.tours, [[1, 2, 3], []])
        self.assertEqual(search.used.tolist(), [False, True, True, True, False, False])
        search.times(0)
        self.assertEqual(search.finish[0], [2, 4, 6])
        self.assertEqual(search.slack[0], [14, 14, 14])
        search.shake(99, 99, False, MT19937_64(1))
        self.assertEqual(search.tours, [[], []])
        self.assertFalse(search.used.any())

    def test_evaluation_and_replay_without_compiler(self):
        here = Path(__file__).resolve().parent
        with tempfile.TemporaryDirectory(dir=str(here)) as directory, \
                patch("EILS.evaluate.build", side_effect=AssertionError("C++ build called")), \
                patch("EILS.evaluate.library", side_effect=AssertionError("C++ library called")), \
                contextlib.redirect_stdout(io.StringIO()):
            output = Path(directory) / "run"
            summary = evaluate(["--backend", "python", "--data", str(here.parent / "data/mrta_gini"),
                                "--num_samples", "1", "--limit", "1", "--progress_every", "0",
                                "--output_dir", str(output)])
            self.assertEqual(summary["backend"], "python")
            self.assertNotIn("compiler", summary["implementation"])
            self.assertNotIn("binary_sha256", summary["implementation"])
            self.assertEqual(verify(output)["solutions_replayed"], 4)

    def test_group_matched_evaluation_visits_each_case_once(self):
        here = Path(__file__).resolve().parent
        with tempfile.TemporaryDirectory(dir=str(here)) as directory, \
                contextlib.redirect_stdout(io.StringIO()):
            summary = evaluate(["--backend", "python", "--data", str(here.parent / "data/mrta_gini"),
                                "--match_taptc_groups", "--num_samples", "2", "--offset", "47",
                                "--limit", "1", "--progress_every", "0", "--output_dir", directory])
            self.assertEqual(summary["profile_mode"], "taptc_matched")
            for model in summary["matched_models"].values():
                self.assertEqual(model["scenarios"], 2)
                self.assertEqual(set(model["by_deadline_group"]), {"tight", "slack"})
            self.assertEqual(verify(directory)["solutions_replayed"], 4)


if __name__ == "__main__":
    unittest.main()
